"""StabilityMap class for generating stability maps for given elements and phases.

This class uses the pycalphad library to calculate the eigenvalues of the Hessian of the Gibbs
energy with respect to the chemical potentials of the components, across a range of compositions,
and plots the results. The resulting map identifies regions of stability and phase separation in
a multi-component system.
"""

from __future__ import annotations

import itertools
import os
import warnings
from concurrent.futures import ProcessPoolExecutor
from typing import TYPE_CHECKING

import numpy as np
import pandas as pd
from pymatgen.core import Composition
